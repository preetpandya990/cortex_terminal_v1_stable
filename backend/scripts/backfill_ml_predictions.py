import asyncio
import logging
import os
import sys
from dataclasses import dataclass
from datetime import datetime, timezone
from decimal import Decimal
from typing import Any

_HERE = os.path.dirname(os.path.abspath(__file__))
_BACKEND = os.path.dirname(_HERE)
if _BACKEND not in sys.path:
    sys.path.insert(0, _BACKEND)

from sqlalchemy import or_, select, update
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker, create_async_engine

from app.core.config import get_settings
from app.ai.fusion.models import AITradingSignal
from app.ai.fusion.signal_assembler import SignalAssembler

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s  %(levelname)-8s  %(message)s",
    datefmt="%H:%M:%S",
)
logger = logging.getLogger("backfill_ml")

# ── Signal fusion helpers (identical to backfill_event_symbols_and_signals) ───

_EVENT_WEIGHT = 0.35
_ML_WEIGHT    = 0.40
_TECH_WEIGHT  = 0.25


def _renormalize_weights(sources: dict[str, tuple[float, bool]]) -> dict[str, float]:
    denom = sum(w for w, avail in sources.values() if avail)
    if denom == 0.0:
        return {k: w for k, (w, _) in sources.items()}
    return {k: (w / denom if avail else 0.0) for k, (w, avail) in sources.items()}


def _fuse(event_signals: dict, ml_signals: dict, technical_signals: dict) -> dict:
    sources = {
        "event":     (_EVENT_WEIGHT, bool(event_signals.get("available", True))),
        "ml":        (_ML_WEIGHT,    bool(ml_signals.get("available", True))),
        "technical": (_TECH_WEIGHT,  bool(technical_signals.get("available", True))),
    }
    weights = _renormalize_weights(sources)
    fused_score = (
        weights["event"]     * event_signals.get("score", 0.0)
        + weights["ml"]      * ml_signals.get("score", 0.0)
        + weights["technical"] * technical_signals.get("score", 0.0)
    )
    fused_conf = (
        weights["event"]     * event_signals.get("confidence", 0.0)
        + weights["ml"]      * ml_signals.get("confidence", 0.0)
        + weights["technical"] * technical_signals.get("confidence", 0.0)
    )
    n_avail = sum(1 for _, avail in sources.values() if avail)
    if n_avail == 1:
        fused_conf = min(fused_conf, 0.85)
    action = "BUY" if fused_score > 50 else "SELL" if fused_score < -50 else "HOLD"
    return {"action": action, "confidence_score": fused_conf, "fused_score": fused_score}


def _build_reasoning(
    action: str, confidence: float, time_horizon: str,
    event_signals: dict, ml_signals: dict,
    regime: str | None, target_price: float | None, stop_loss: float | None,
) -> str:
    _BANDS = [(0.80, "high"), (0.60, "medium"), (0.0, "low")]
    band = next(label for thr, label in _BANDS if confidence >= thr)
    dominant = "ML ensemble" if ml_signals.get("score", 0.0) != 0.0 else "event analysis"
    ml_conf_pct = f"{ml_signals.get('confidence', 0.0) * 100:.0f}%"
    event_count = event_signals.get("event_count", 0)
    parts = [
        f"{time_horizon.capitalize()} {action.capitalize()} ({band} confidence · {confidence * 100:.1f}%):",
        f"{dominant} projects {'bullish' if action == 'BUY' else 'bearish' if action == 'SELL' else 'neutral'}"
        f" momentum with {ml_conf_pct} confidence.",
    ]
    if event_count > 0:
        parts.append(f"{event_count} recent market event{'s' if event_count > 1 else ''} reinforce the setup.")
    if regime and regime != "unknown":
        parts.append(f"Market regime: {regime.replace('_', ' ')}.")
    if stop_loss:
        parts.append(f"Stop loss: ₹{stop_loss:,.2f}.")
    if target_price:
        parts.append(f"Target: ₹{target_price:,.2f}.")
    return " ".join(parts)


# ── Stats ──────────────────────────────────────────────────────────────────────

@dataclass
class BackfillStats:
    examined:       int = 0
    updated:        int = 0
    skipped:        int = 0   # insufficient OHLCV data
    errors:         int = 0
    action_changes: int = 0


# ── Main backfill ──────────────────────────────────────────────────────────────

async def run_backfill(
    session_factory: async_sessionmaker,
    redis,
    ml_components: dict,
    since: datetime,
    dry_run: bool,
    batch_size: int,
) -> BackfillStats:
    stats = BackfillStats()

    _ml_predictor  = ml_components["ensemble_predictor"]
    _seq_len       = ml_components["ensemble_sequence_length"]
    _n_features    = ml_components["ensemble_n_features"]
    _feature_names = ml_components["ensemble_feature_names"]

    # Fetch all eligible IDs upfront
    async with session_factory() as db:
        id_rows = await db.execute(
            select(AITradingSignal.id)
            .where(
                AITradingSignal.created_at >= since,
                or_(
                    AITradingSignal.ml_predictions.is_(None),
                    AITradingSignal.ml_predictions["available"].as_string() == "false",
                ),
            )
            .order_by(AITradingSignal.id)
        )
        all_ids = [r[0] for r in id_rows.all()]

    total = len(all_ids)
    logger.info("Signals to process: %d", total)

    assembler = SignalAssembler(
        ensemble_predictor=_ml_predictor,
        feature_loader=None,   # injected per cycle
        redis=redis,
    )

    for batch_start in range(0, total, batch_size):
        batch_ids = all_ids[batch_start : batch_start + batch_size]

        async with session_factory() as db:
            try:
                from app.ml.inference.feature_loader import FeatureLoader

                rows = await db.execute(
                    select(
                        AITradingSignal.id,
                        AITradingSignal.symbol,
                        AITradingSignal.action,
                        AITradingSignal.signal_timestamp,
                        AITradingSignal.time_horizon,
                        AITradingSignal.regime_type,
                        AITradingSignal.target_price,
                        AITradingSignal.stop_loss,
                        AITradingSignal.contributing_events,
                        AITradingSignal.technical_indicators,
                    )
                    .where(AITradingSignal.id.in_(batch_ids))
                )
                signals = rows.all()

                updates: list[dict[str, Any]] = []

                # Bind one FeatureLoader for this batch (shared DB session)
                assembler.feature_loader = FeatureLoader(
                    db=db,
                    redis=redis,
                    sequence_length=_seq_len,
                    n_features=_n_features,
                    feature_names=_feature_names,
                )

                for sig in signals:
                    stats.examined += 1
                    try:
                        # Always use "1d" OHLCV granularity for inference.
                        # sig.time_horizon ("swing", "intraday", "positional") is
                        # a signal validity horizon, not an OHLCV granularity string —
                        # passing it to gather_ml_signals would return 0 OHLCV rows.
                        ml_signals = await assembler.gather_ml_signals(
                            db=db,
                            symbol=sig.symbol,
                            timeframe="1d",
                        )

                        if not ml_signals.get("available"):
                            stats.skipped += 1
                            continue

                        # Reconstruct event and technical signals from stored JSONB
                        # so we can re-fuse all three components correctly.
                        # gather_event_signals with reference_time gives the correct
                        # historical event picture; technical is already stored.
                        event_signals = await assembler.gather_event_signals(
                            db=db,
                            symbol=sig.symbol,
                            reference_time=sig.signal_timestamp,
                        )
                        tech_signals: dict = dict(sig.technical_indicators or {})

                        fused = _fuse(event_signals, ml_signals, tech_signals)

                        target = float(sig.target_price) if sig.target_price else None
                        sl     = float(sig.stop_loss)    if sig.stop_loss    else None
                        reasoning = _build_reasoning(
                            action=fused["action"],
                            confidence=fused["confidence_score"],
                            time_horizon=sig.time_horizon or "swing",
                            event_signals=event_signals,
                            ml_signals=ml_signals,
                            regime=sig.regime_type,
                            target_price=target,
                            stop_loss=sl,
                        )

                        action_changed = fused["action"] != sig.action
                        if action_changed:
                            stats.action_changes += 1

                        updates.append({
                            "id":              sig.id,
                            "ml_predictions":  ml_signals,
                            "confidence_score": round(fused["confidence_score"], 2),
                            "action":          fused["action"],
                            "reasoning":       reasoning,
                            "old_action":      sig.action,
                            "ml_conf":         ml_signals.get("confidence", 0.0),
                        })

                    except Exception as exc:
                        logger.warning("  signal id=%d (%s) error: %s", sig.id, sig.symbol, exc)
                        stats.errors += 1

                assembler.feature_loader = None

                if dry_run:
                    for u in updates:
                        action_note = (
                            f"  ACTION {u['old_action']}→{u['action']}"
                            if u["old_action"] != u["action"] else ""
                        )
                        logger.info(
                            "  [DRY-RUN] id=%-7d  ml_conf=%.3f  fused_conf=%.3f%s",
                            u["id"], u["ml_conf"], u["confidence_score"], action_note,
                        )
                    stats.updated += len(updates)
                else:
                    for u in updates:
                        await db.execute(
                            update(AITradingSignal)
                            .where(AITradingSignal.id == u["id"])
                            .values(
                                ml_predictions=u["ml_predictions"],
                                confidence_score=Decimal(str(u["confidence_score"])),
                                action=u["action"],
                                reasoning=u["reasoning"],
                            )
                        )
                    await db.commit()
                    stats.updated += len(updates)

            except Exception as exc:
                logger.error("Batch %d–%d failed: %s", batch_start, batch_start + batch_size, exc)
                assembler.feature_loader = None
                await db.rollback()
                stats.errors += batch_size

        pct = min(batch_start + batch_size, total)
        logger.info(
            "  Progress: %d/%d  updated=%d  skipped=%d  action_changes=%d  errors=%d",
            pct, total, stats.updated, stats.skipped, stats.action_changes, stats.errors,
        )

    return stats


async def main(since: datetime, dry_run: bool, batch_size: int) -> None:
    settings = get_settings()

    engine = create_async_engine(
        str(settings.DATABASE_URL),
        pool_size=5,
        max_overflow=2,
        pool_pre_ping=True,
        connect_args={"server_settings": {"timezone": "UTC"}},
    )
    session_factory = async_sessionmaker(
        engine, class_=AsyncSession,
        expire_on_commit=False, autocommit=False, autoflush=False,
    )

    mode = "[DRY-RUN]" if dry_run else "[LIVE]"
    logger.info("=" * 65)
    logger.info("Backfill: ML Predictions  %s", mode)
    logger.info("Since:      %s", since.date())
    logger.info("Batch size: %d", batch_size)
    logger.info("=" * 65)

    try:
        # ── Load Redis ─────────────────────────────────────────────────────────
        from app.core.redis import init_redis, get_cache_service
        await init_redis()
        redis_svc = get_cache_service()
        redis = redis_svc._redis

        # ── Load ML models ─────────────────────────────────────────────────────
        logger.info("Loading ML models from registry...")
        from app.ml.inference.registry_loader import RegistryModelLoader
        from app.ml.inference.ensemble_predictor import EnsemblePredictor

        async with session_factory() as session:
            loader   = RegistryModelLoader(session=session, num_threads=4)
            ensemble = await loader.load_production_ensemble()

        predictor = EnsemblePredictor.from_loaded_ensemble(ensemble, cache=redis_svc)
        ml_components = {
            "ensemble_predictor":       predictor,
            "ensemble_sequence_length": ensemble.sequence_length,
            "ensemble_n_features":      ensemble.n_features,
            "ensemble_feature_names":   ensemble.feature_names,
        }
        logger.info(
            "ML loaded: XGBoost v%s + GRU v%s | features=%d seq_len=%d",
            ensemble.xgboost_version, ensemble.gru_version,
            ensemble.n_features, ensemble.sequence_length,
        )

        # ── Run backfill ───────────────────────────────────────────────────────
        stats = await run_backfill(
            session_factory, redis, ml_components,
            since, dry_run, batch_size,
        )

        logger.info("")
        logger.info("=" * 65)
        logger.info("Results:")
        logger.info("  Examined       : %d", stats.examined)
        logger.info("  Updated        : %d", stats.updated)
        logger.info("  Skipped        : %d  (insufficient OHLCV data)", stats.skipped)
        logger.info("  Action changes : %d", stats.action_changes)
        logger.info("  Errors         : %d", stats.errors)
        if dry_run:
            logger.info("")
            logger.info("DRY-RUN complete — no data written. Re-run without --dry-run to apply.")
        else:
            logger.info("")
            logger.info("Backfill complete: %d signals updated.", stats.updated)
        logger.info("=" * 65)

    finally:
        from app.core.redis import close_redis
        await close_redis()
        await engine.dispose()


def _parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Backfill ML predictions for signals with available=false.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument("--dry-run", action="store_true", help="Preview without writing.")
    p.add_argument("--since", default="2026-05-30", metavar="YYYY-MM-DD")
    p.add_argument("--batch-size", type=int, default=50, metavar="N")
    return p.parse_args()


if __name__ == "__main__":
    args = _parse_args()
    since_dt = datetime.fromisoformat(args.since).replace(tzinfo=timezone.utc)
    asyncio.run(main(since=since_dt, dry_run=args.dry_run, batch_size=args.batch_size))
