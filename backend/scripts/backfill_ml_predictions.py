#!/usr/bin/env python3
"""
Backfill: ML Predictions for ai_trading_signals with available=false
====================================================================
1,115 signals generated by the event_processing_loop have
ml_predictions = {available: false} because the feature_loader was
never passed to the SignalAssembler (worker bug fixed in the same
commit as this script).

For each affected signal this script:
  1. Loads features from upstox_ohlcv (same pipeline as live inference).
  2. Runs XGBoost + GRU ensemble prediction.
  3. Writes ml_predictions, then re-fuses the signal so
     confidence_score, action, and reasoning all reflect the
     corrected three-source (event + ML + technical) weights.

Only signals where ml_predictions->>'available' = 'false' are touched.

Safety
------
  • Idempotent: only processes signals with available=false.
  • Dry-run (--dry-run): prints proposed changes without DB writes.
  • Batched: configurable batch size (default 50).
  • Skip-on-error: a single failed symbol never blocks the batch.
  • Atomic per batch: commit or rollback together.

Usage
-----
  python scripts/backfill_ml_predictions.py --dry-run
  python scripts/backfill_ml_predictions.py
  python scripts/backfill_ml_predictions.py --since 2026-05-30 --batch-size 25
"""
